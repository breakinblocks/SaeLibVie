    static {
        for (int i = 0; i < 16; i++) {
            int j = (i >> 3 & 1) * 85;
            int r = (i >> 2 & 1) * 170 + j;
            int g = (i >> 1 & 1) * 170 + j;
            int b = (i & 1) * 170 + j;
            if (i == 6) r += 85;
            CHAT[i] = Color.rgb(r, g, b);
        }
        String[] parts = PALETTE_HEX.trim().split("\\s+");
        for (int i = 0; i < 256; i++) {
            PALETTE[i] = Color.rgb(Integer.parseInt(parts[i], 16));
        }
    }

    private ColorTables() {
    }

    public static Color chat(int index) {
        return CHAT[index & 15];
    }

    public static Color chat(@Nullable ChatFormatting formatting) {
        if (formatting == null) return Color.WHITE;
        return CHAT[formatting.ordinal() & 15];
    }

    public static Color get256(int id) {
        return PALETTE[id & 255];
    }

    public static Color[] chatColors() {
        return CHAT.clone();
    }

    public static Color[] palette256() {
        return PALETTE.clone();
    }
